// Regenerates src/abi/index.ts (typed `as const` ABIs) from the JSON files exported by
// contracts/script/export-abis.sh. Run: node scripts/gen-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "abi");
const names = { ClinchHook: "hookAbi", ClinchLaunch: "launchAbi", ClinchLaunchFactory: "factoryAbi", MockERC20: "erc20Abi", HumanGate: "humanGateAbi" };
let out = "// AUTO-GENERATED by scripts/gen-abi.mjs from src/abi/*.json. Do not edit.\n\n";
for (const [file, name] of Object.entries(names)) {
  let abi = JSON.parse(readFileSync(join(dir, `${file}.json`), "utf8"));
  if (!Array.isArray(abi)) abi = abi.abi;
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(dir, "index.ts"), out);
console.log("wrote src/abi/index.ts");
